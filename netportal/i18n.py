def pick(accept_language):
    """The best language for an Accept-Language header (ru -> uk, default en)."""
    for part in (accept_language or "").split(","):
        code = part.split(";")[0].strip().lower()[:2]
        if code in TEXT:
            return code
        if code == "ru":
            return "uk"
    return "en"
